#!/usr/bin/env python3
"""Refresh state/meta.json for every catalogued repo and log what changed.

Stage 1, every repo: one `git ls-remote` (HEAD and tags). Unchanged -> nothing else happens.
Stage 2, only when HEAD or tags moved: a blobless depth-1 clone reads the commit date, licence, pak.json and file
counts (common.read_repo). No API token needed.

Changes go to state/changes.json (events, kept 120 days) and state/CHANGES.md (everything since the last review,
see docs/UPDATING.md). `--ack` marks everything up to now as reviewed.

  python3 scripts/check_updates.py            # check all
  python3 scripts/check_updates.py --only ozma grainbrick
  python3 scripts/check_updates.py --ack      # after reading state/CHANGES.md
"""
from __future__ import annotations

import argparse
import concurrent.futures as cf
import datetime as dt
import hashlib

from common import STATE, TODAY, load_json, ls_remote, projects, read_repo, write_json, write_text

META = STATE / "meta.json"
EVENTS = STATE / "changes.json"
REVIEWED = STATE / "reviewed.txt"


def tagset(tags):
    return hashlib.sha1("\n".join(sorted(tags)).encode()).hexdigest()[:12]


def version_key(t):
    import re
    nums = [int(x) for x in re.findall(r"\d+", t)[:4]]
    return nums + [0] * (4 - len(nums))


def check(entry, old):
    url = entry["repo"]
    try:
        rem = ls_remote(url)
    except Exception as e:  # repo gone, renamed or private
        return url, old, [{"what": "unreachable", "detail": str(e)[:160]}] if not old.get("unreachable") else []
    new = dict(old)
    ev = []
    if old.get("unreachable"):
        new.pop("unreachable", None)
        ev.append({"what": "back online"})
    ts = tagset(rem["tags"])
    if rem["head"] == old.get("head") and ts == old.get("tagset"):
        return url, new, ev
    try:
        info = read_repo(url, want_readme=False)
    except Exception as e:
        return url, old, [{"what": "read error", "detail": str(e)[:160]}]
    new.update({k: v for k, v in info.items() if k != "readme"})
    new["tagset"] = ts
    alltags = sorted(rem["tags"], key=version_key)
    new["tags"] = alltags[-5:]
    added = sorted(set(rem["tags"]) - set(old.get("tags_all", [])), key=version_key) if old.get("tags_all") is not None else []
    new["tags_all"] = alltags[-60:]
    if old.get("head"):  # not the first look
        for t in added[-3:]:
            ev.append({"what": "release", "detail": t})
        if info.get("last_commit") != old.get("last_commit") and not added:
            ev.append({"what": "commits", "detail": f"last commit {info.get('last_commit')}"})
        if (info.get("license") or None) != (old.get("license") or None):
            ev.append({"what": "licence", "detail": f"{old.get('license')} -> {info.get('license')}"})
        ov, nv = (old.get("pak") or {}).get("version"), (info.get("pak") or {}).get("version")
        if nv and nv != ov and not any(e["what"] == "release" for e in ev):
            ev.append({"what": "release", "detail": f"pak.json {nv}"})
    new["checked"] = TODAY.isoformat()
    return url, new, ev


def render_changes(events, reviewed):
    byid = {p["id"]: p for p in projects()}
    rows = [e for e in events if e["date"] > reviewed]
    lines = ["# Changes since the last review", "", f"Last review: {reviewed}. Generated by scripts/check_updates.py;"
             " read docs/UPDATING.md, then run `python3 scripts/check_updates.py --ack`.", ""]
    if not rows:
        lines.append("Nothing to do.")
    for e in sorted(rows, key=lambda e: (e["date"], e["id"])):
        p = byid.get(e["id"], {})
        lines.append(f"- {e['date']} **{e['id']}** ({p.get('category', '?')}): {e['what']}"
                     + (f" - {e['detail']}" if e.get("detail") else "") + f" <{p.get('repo', '')}>")
    write_text(STATE / "CHANGES.md", "\n".join(lines) + "\n")
    return len(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--ack", action="store_true")
    ap.add_argument("--workers", type=int, default=8)
    a = ap.parse_args()
    events = load_json(EVENTS, [])
    reviewed = REVIEWED.read_text().strip() if REVIEWED.exists() else "2026-11-24"
    if a.ack:
        REVIEWED.write_text(TODAY.isoformat() + "\n")
        render_changes(events, TODAY.isoformat())
        print("reviewed up to", TODAY)
        return
    meta = load_json(META, {})
    todo = [p for p in projects() if p.get("repo") and (not a.only or p["id"] in a.only)]
    idof = {p["repo"]: p["id"] for p in todo}
    n_changed = 0
    with cf.ThreadPoolExecutor(a.workers) as ex:
        for url, new, ev in ex.map(lambda p: check(p, meta.get(p["repo"], {})), todo):
            if ev and ev[0]["what"] == "unreachable":
                new = dict(meta.get(url, {}), unreachable=TODAY.isoformat())
            meta[url] = new
            for e in ev:
                events.append({"date": TODAY.isoformat(), "id": idof[url], **e})
            n_changed += bool(ev)
    cutoff = (TODAY - dt.timedelta(days=120)).isoformat()
    events = [e for e in events if e["date"] >= cutoff]
    # drop metadata of repos no longer catalogued
    live = {p["repo"] for p in projects()}
    meta = {k: v for k, v in meta.items() if k in live}
    write_json(META, dict(sorted(meta.items())))
    write_json(EVENTS, events)
    n = render_changes(events, reviewed)
    print(f"checked {len(todo)} repos, {n_changed} changed; {n} change(s) waiting for review")


if __name__ == "__main__":
    main()
